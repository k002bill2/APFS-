export const detailId = (gcode: string, code: string): string => `${gcode}:${code}`;

/** 데모 코드구분 — 호출마다 새 배열(로컬 state 초기값·새로고침 복원용) */
export function demoGroups(): CodeGroup[] {
  return GROUPS.map(([code, name, rem, up]) => ({ id: code, code, name, up: up ?? '', rem, use: true }));
}
/** 데모 코드상세 — 코드구분별 배열(정렬 = 원문 순서) */
export function demoDetails(): Record<string, CodeDetail[]> {
  const out: Record<string, CodeDetail[]> = {};
  for (const [g, list] of Object.entries(DETAILS)) {
    out[g] = list.map(([code, name, rem], i) => ({ id: detailId(g, code), gcode: g, code, name, en: '', ord: i + 1, rem, use: true, by: SEED_BY, at: SEED_AT }));
  }
  return out;
}

/** 코드구분 삭제 게이트 — 막는 사유를 돌려준다(없으면 null). 코드상세가 있거나, 다른 코드구분이 이 코드를 상위로 참조하면 삭제 불가
    (참조가 남으면 상위코드구분 컬럼·모달 select 가 존재하지 않는 코드를 가리킨다). 요청 시점과 확인 다이얼로그 실행 시점 둘 다 검사한다. */
export type GroupDeleteBlocker = '코드상세' | '하위 코드구분';
export function groupDeleteBlocker(groups: readonly CodeGroup[], details: Readonly<Record<string, readonly CodeDetail[]>>, code: string): GroupDeleteBlocker | null {
  if ((details[code] ?? []).length) return '코드상세';
  if (groups.some((g) => g.up === code)) return '하위 코드구분';
  return null;
}
