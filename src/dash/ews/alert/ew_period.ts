/* 조기경보 조회 3화면(운용사별 S2_47 · 자펀드별 S2_49 · 전월 비교 S2_63)의 기준년월 판정.
   2026-11-17 사용자 지시 "기준년월이 표를 거르게"(종전엔 행을 거르지 않는 조회 기준 컨텍스트였다).

   - 원문 행 = 목업 검색박스 기준년월(`value="2026-07"`) 시점의 결과다 → EW_BASE_YM.
   - 기준년월 칸은 기본값이 없다(2026-09-21 사용자 결정 "기준년월 디폴트 없애줘").
     **비어 있으면 원문 시점으로 본다** — 평가 결과는 시점마다 한 벌인 스냅샷이라 두 시점을 섞어 보이지 않는다.
     그래서 첫 화면(빈 칸)은 종전과 같은 원문 행이고, 칩·푸터·파일명의 빈 값 처리도 그대로다.
   - 직전월(EW_PREV_YM) 결과는 화면마다 창작 더미(원문 아님)를 둔다 — 그 밖의 달은 0건이 정상이다. */
export const EW_BASE_YM = '2026-07';
export const EW_PREV_YM = '2026-06';

/** 조회 시점 — 빈 값 = 원문 시점 */
export const ewYm = (fYm: string): string => fYm || EW_BASE_YM;

/** 스냅샷 판정 — 행의 평가 기준년월이 조회 시점과 같은 달인가 */
export const atEwYm = (rowYm: string, fYm: string): boolean => rowYm === ewYm(fYm);
